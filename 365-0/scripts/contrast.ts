// `npm run contrast`: fails if any token pair drops below its WCAG limit or two day-type colours become
// too close under colour-blindness simulation. `--docs` also rewrites docs/tokens.md.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  CVD_MIN_DELTA_E,
  DAY_TOKENS,
  GRAPHIC_MIN,
  TEXT_MIN,
  VISIONS,
  checkCvd,
  checkPairs,
  hex,
  oklchText,
  parseTokens,
} from './lib/tokens.ts';

const root = join(import.meta.dirname, '..');
const css = readFileSync(join(root, 'src/styles/tokens.css'), 'utf8');
const tokens = parseTokens(css);
const pairs = checkPairs(tokens);
const cvd = checkCvd(tokens);

const failures = [...pairs.filter((p) => !p.ok), ...cvd.filter((c) => !c.ok)];
for (const p of pairs.filter((x) => !x.ok)) {
  console.error(
    `FAIL ${p.theme}: ${p.fg} on ${p.bg} is ${p.ratio.toFixed(2)}:1, needs ${String(p.min)}:1 (${p.what})`,
  );
}
for (const c of cvd.filter((x) => !x.ok)) {
  console.error(
    `FAIL ${c.vision}: ${c.a} and ${c.b} are ${c.distance.toFixed(3)} apart, need ${String(CVD_MIN_DELTA_E)}`,
  );
}

const worst = (vision: string): number =>
  Math.min(...cvd.filter((c) => c.vision === vision).map((c) => c.distance));
console.log(
  `contrast: ${String(pairs.length)} pairs checked (lowest ratio ${Math.min(...pairs.map((p) => p.ratio)).toFixed(2)}:1); ` +
    `day-type distance ${VISIONS.map((v) => `${v} ${worst(v).toFixed(3)}`).join(', ')}`,
);

if (process.argv.includes('--docs')) {
  const lines: string[] = [];
  const out = (s = ''): void => {
    lines.push(s);
  };
  out('# Design tokens');
  out();
  out(
    'Generated by `npm run contrast -- --docs` from `src/styles/tokens.css`. Do not edit by hand.',
  );
  out();
  out('## Colour');
  out();
  out('| token | light hex | light OKLCH | dark hex | dark OKLCH |');
  out('| --- | --- | --- | --- | --- |');
  for (const name of [
    '--surface',
    '--raised',
    '--ink',
    '--ink-muted',
    '--well',
    '--on-well',
    '--on-well-muted',
    '--accent',
    '--on-accent',
    ...DAY_TOKENS,
  ]) {
    out(
      `| \`${name}\` | ${hex(tokens, name, 'light')} | ${oklchText(tokens, name, 'light')} | ${hex(tokens, name, 'dark')} | ${oklchText(tokens, name, 'dark')} |`,
    );
  }
  out();
  out(
    "`--border` is the ink colour at 12 percent and `--border-strong` at 45 percent (`color-mix`). Borders are structural: every card, button and chip also carries a text label, so no meaning depends on a border's contrast.",
  );
  out();
  out('## Deviations from the SPEC hex targets');
  out();
  out(
    'The year grid sits on a dark panel (`--well`) in both themes, so all six day colours have the same background and meet 3:1 against it. Lightness was adjusted from the SPEC targets so the six stay apart under colour-blindness simulation:',
  );
  out();
  out('| day type | SPEC target | used | reason |');
  out('| --- | --- | --- | --- |');
  out('| perfect | #FFB703 | unchanged | |');
  out(
    '| ok | #B8C4CF (dark #3B4A5E) | one value for both themes | the grid panel is dark in both themes; slightly darker so it separates from freeze and storm |',
  );
  out('| rain | #2F6FDE | unchanged | |');
  out(
    '| storm | #6A3DC8 | lighter violet | the target was 2.4 to 2.8:1 on the panel, below 3:1, and too close to rain for deuteranopia |',
  );
  out('| heat | #F0502A | unchanged | |');
  out(
    '| freeze | #5CC8E8 | paler cyan | the target was almost the same as ok for protanopia (distance 0.04) |',
  );
  out();
  out(`## Contrast (text ${String(TEXT_MIN)}:1, graphics ${String(GRAPHIC_MIN)}:1)`);
  out();
  out('| foreground | background | use | needs | light | dark |');
  out('| --- | --- | --- | --- | --- | --- |');
  const seen = new Set<string>();
  for (const p of pairs) {
    const key = `${p.fg}|${p.bg}|${String(p.min)}`;
    if (seen.has(key)) continue;
    seen.add(key);
    const light = pairs.find(
      (x) => x.theme === 'light' && x.fg === p.fg && x.bg === p.bg && x.min === p.min,
    );
    const dark = pairs.find(
      (x) => x.theme === 'dark' && x.fg === p.fg && x.bg === p.bg && x.min === p.min,
    );
    out(
      `| \`${p.fg}\` | \`${p.bg}\` | ${p.what} | ${String(p.min)}:1 | ${(light?.ratio ?? 0).toFixed(2)}:1 | ${(dark?.ratio ?? 0).toFixed(2)}:1 |`,
    );
  }
  out();
  out('## Colour-blindness simulation');
  out();
  out(
    `Machado et al. (2009) matrices at full severity. Distance is Euclidean in OKLab (about 0.02 is barely visible, 0.1 is clear); every pair of the six day types must stay at least ${String(CVD_MIN_DELTA_E)} apart. Pattern mode adds a second cue to the four loss types.`,
  );
  out();
  out('| vision | closest pair | distance |');
  out('| --- | --- | --- |');
  for (const v of VISIONS) {
    const closest = cvd
      .filter((c) => c.vision === v)
      .reduce((a, b) => (b.distance < a.distance ? b : a));
    out(
      `| ${v} | ${closest.a.slice(6)} and ${closest.b.slice(6)} | ${closest.distance.toFixed(3)} |`,
    );
  }
  out();
  writeFileSync(join(root, 'docs/tokens.md'), lines.join('\n'));
  console.log('contrast: wrote docs/tokens.md');
}

if (failures.length > 0) {
  console.error(`contrast: ${String(failures.length)} failure(s)`);
  process.exit(1);
}
